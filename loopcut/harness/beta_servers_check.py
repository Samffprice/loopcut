def check(ok, message):
    if not ok:
        raise AssertionError(message)
    print('PASS ' + message, flush=True)


class ProductionStub(BaseHTTPRequestHandler):
    """Today's three gateway routes; all other paths return Next-style HTML 404s."""
    def log_message(self, *_):
        pass

    def dispatch(self):
        body = self.rfile.read(int(self.headers.get('Content-Length', 0)))
        self.server.requests.append({'path': self.path, 'method': self.command,
            'headers': {k.lower(): v for k, v in self.headers.items()},
            'body': json.loads(body) if body else None})
        path = urlsplit(self.path).path
        status, content_type = 200, 'application/json'
        if self.command == 'GET' and path == '/v1/models':
            data = json.dumps({'object': 'list', 'default': 'fast', 'data': [
                {'id': name, 'object': 'model', 'owned_by': 'loopcut', 'display_name': name.title(),
                 'available': True, 'default': name == 'fast', 'keep_context': False,
                 'usage_multiplier': 1, 'plans': ['pro'], 'unlock_plan': None}
                for name in ('fast', 'pro')]}).encode()
        elif self.command == 'GET' and path == '/v1/me':
            data = json.dumps({'email': 'smoke@example.test', 'name': 'Smoke', 'plan': 'pro',
                'session': {'used': 0, 'resets_at': None}, 'week': {'used': 0, 'resets_at': None}}).encode()
        elif self.command == 'POST' and path == '/v1/chat/completions':
            content_type = 'text/event-stream'
            data = b'data: {"choices":[{"delta":{"content":"Smoke reply."},"finish_reason":"stop"}]}\n\ndata: [DONE]\n\n'
        else:
            status, content_type = 404, 'text/html; charset=utf-8'
            data = b'<!DOCTYPE html><html><body><h1>404</h1>This page could not be found.</body></html>'
        self.send_response(status)
        self.send_header('Content-Type', content_type)
        self.send_header('Content-Length', str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    do_GET = do_POST = do_PATCH = dispatch


@contextmanager
def prod_stub():
    server = ThreadingHTTPServer(('127.0.0.1', 0), ProductionStub)
    server.requests = []
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield f'http://127.0.0.1:{server.server_port}', server.requests
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)


@contextmanager
def platform_mock(path, directory):
    if not path.is_file():
        raise ValueError('Platform mock not found; use --mock-path')
    with socket.socket() as sock:
        sock.bind(('127.0.0.1', 0))
        port = sock.getsockname()[1]
    # -B keeps the read-only platform checkout free of generated bytecode.
    with (directory / 'mock.log').open('w+') as log:
        process = subprocess.Popen([sys.executable, '-B', str(path), '--port', str(port)],
                                   stdout=log, stderr=log)
        try:
            deadline = time.monotonic() + 15
            while True:
                if process.poll() is not None or time.monotonic() >= deadline:
                    log.seek(0)
                    raise RuntimeError('Mock did not start: ' + log.read()[-2000:])
                try:
                    with socket.create_connection(('127.0.0.1', port), timeout=.2):
                        break
                except OSError:
                    time.sleep(.05)
            yield f'http://127.0.0.1:{port}'
        finally:
            process.terminate()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=5)


def fake_blender(directory):
    bpy = ModuleType('bpy')
    bpy.types = SimpleNamespace(**{name: type(name, (), {}) for name in (
        'Operator', 'AddonPreferences', 'Menu', 'FileHandler', 'OperatorFileListElement', 'SpaceLoopcut')})
    bpy.props, bpy.ops = Mock(), Mock()
    timers = set()
    bpy.app = SimpleNamespace(version=(5, 2, 0), driver_namespace={}, cachedir=str(directory), binary_path='',
        background=False,
        timers=SimpleNamespace(is_registered=lambda fn: fn in timers,
            register=lambda fn, **_: timers.add(fn), unregister=timers.discard))
    area = SimpleNamespace(type='LOOPCUT', as_pointer=lambda: 1, tag_redraw=lambda: None)
    bpy.context = SimpleNamespace(area=area, region=SimpleNamespace(width=640, height=900),
        preferences=SimpleNamespace(system=SimpleNamespace(ui_scale=1), addons={}),
        scene={}, view_layer=None, window_manager=SimpleNamespace(
            windows=[SimpleNamespace(screen=SimpleNamespace(areas=[area]))]))
    bpy.utils = ModuleType('bpy.utils')
    bpy.utils.previews = ModuleType('bpy.utils.previews')
    return bpy


def wait_for_cloud(modules, errors):
    deadline = time.monotonic() + 15
    while any(t.name in ('loopcut-manifest', 'loopcut-interest', 'loopcut-votes', 'loopcut-vote')
              for t in threading.enumerate()):
        modules.mainthread._pump()
        if time.monotonic() >= deadline:
            raise AssertionError('Cloud background task timed out')
        time.sleep(.005)
    modules.mainthread._pump()
    if errors:
        raise AssertionError('Cloud background task raised') from errors[0]


VOTE_WAYS = {'votes': 'PUT /v1/votes (contract 0.7)', 'interest': 'no votes here: the interest event stands in',
             'refused': 'refused; the pick went back with a notice'}


def rendered_hits(host):
    return {hit['id']: hit['action'] for hit in host.draw.render.call_args.args[0]['hits']}


def vote_click(m, host, session, requests, errors, name, signed_in):
    """Open the vote view from the strip and vote for `name`, as a tester would, then check the request for
    whichever the server supports: PUT /v1/votes/<name> {app_version, install_id}, or on a server without
    votes the interest event it stands in for. Signed out, the server may still refuse anonymous calls.
    Leaves the vote view open; returns 'votes', 'interest' or 'refused'."""
    who = 'signed in' if signed_in else 'signed out'
    host.draw_area()
    check(rendered_hits(host).get('vote.strip') == ('votes_open', None), who + ': the chat view has the vote strip')
    host._do_action(session, ('votes_open', None))
    wait_for_cloud(m, errors)
    host.draw_area()
    hits = rendered_hits(host)
    check(hits.get('vote.' + name) == ('vote', name), who + ': the vote view has the vote action')
    check((hits.get('vote.signin') == ('sign_in', 'loopcut')) != signed_in,
          who + ': the vote view asks to sign in only when signed out')
    if signed_in and name in m.cloud._runtime.votes['mine']:
        # Sign-in adopts the install's anonymous votes (SPEC §3.11), so the signed-out vote is already this
        # account's: take it back first, then vote as a signed-in tester would.
        start = len(requests)
        host._do_action(session, ('vote', name))
        wait_for_cloud(m, errors)
        taken = [r['method'] for r in requests[start:] if r['path'] == '/v1/votes/' + name]
        check(taken == ['DELETE'] and name not in m.cloud._runtime.votes['mine'],
              who + ': the vote adopted at sign-in can be taken back')
    start = len(requests)
    host._do_action(session, ('vote', name))
    wait_for_cloud(m, errors)
    runtime, install_id = m.cloud._runtime, m.credentials.interest_install_id()
    sent = requests[start:]
    puts = [r for r in sent if r['path'] == '/v1/votes/' + name]
    events = [r for r in sent if r['path'] == '/v1/events']
    check(sent and all(r['auth'] == signed_in for r in sent),
          who + (': the vote carries the bearer' if signed_in else ': the vote has no Authorization'))
    vote_body = {'app_version': m.config.app_version(), 'install_id': install_id}
    ok = len(puts) <= 1 and all(r['method'] == 'PUT' and r['body'] == vote_body for r in puts)
    if runtime.votes['server'] is True:
        way = 'votes'
        ok = ok and len(puts) == 1 and not events and name in runtime.votes['mine']
    elif runtime.votes['server'] is False:
        # One event; a contract 0.5 server refuses the 0.6 fields and gets one 0.5-shaped resend.
        way = 'interest'
        ok = ok and 1 <= len(events) <= 2 and name in runtime.votes['mine'] and events[0]['body'] == {
            'type': 'interest', 'tool': name, 'source': 'coming_soon_button', 'install_id': install_id,
            'app_version': m.config.app_version()}
        if ok:
            print(f'NOTE {who} interest on this server: {runtime.interests.get(name)}', flush=True)
    else:
        way = 'refused'
        ok = (ok and not signed_in and len(puts) == 1 and not events and name not in runtime.votes['mine']
              and m.cloud.vote_notice() in (m.cloud.VOTE_SIGN_IN_NOTICE, m.cloud.VOTE_FAILED_NOTICE))
    check(ok, who + ': the vote click sent the right request for this server')
    print(f'NOTE {who} vote on this server: {VOTE_WAYS[way]}', flush=True)
    return way


def leave_votes(host, session):
    back = rendered_hits(host).get('vote.back')
    check(back == ('history_close', None), 'the vote view has a way back to the chat')
    host._do_action(session, back)


def signed_out_click(m, host, requests, errors, mode):
    """A ChatGPT-plan tester: never signed in to Loopcut. Rows come from the public manifest; a vote goes
    out without Authorization and with the random install id (the server may still refuse anonymous calls
    until its flag is on: then the pick goes back with a notice, and the vote view asks to sign in)."""
    runtime = m.cloud._runtime
    check(not runtime.signed_in, 'signed out before sign-in')
    runtime.refresh()
    session = m.state.session()
    host.draw_area()
    rows = [row['name'] for row in host._cloud_panel_state(session)['coming_soon']]
    if mode == 'prod':
        check(not rows, 'signed out: an older service shows no coming-soon rows')
    else:
        check(bool(rows), 'signed out: coming-soon rows render from the public manifest')
    if not rows:
        return rows
    vote_click(m, host, session, requests, errors, rows[0], signed_in=False)
    leave_votes(host, session)
    return rows


def exercise(url, key, mode, directory, server_requests=None):
    origin = url.rstrip('/').removesuffix('/v1')
    env = {k: v for k, v in os.environ.items() if not k.startswith('LOOPCUT_')}
    env.update(LOOPCUT_SERVICE_URL=origin, LOOPCUT_SERVICE_URLS=origin + '/v1',
        LOOPCUT_BASE_URL=origin + '/v1', LOOPCUT_API_KEY=key, LOOPCUT_MODEL='fast',
        LOOPCUT_CONFIG_DIR=str(directory / 'config'), LOOPCUT_DATA_DIR=str(directory / 'data'),
        LOOPCUT_WORKSPACE='false', LOOPCUT_CODEX_APP='false', LOOPCUT_MAX_STEPS='2')
    bpy = fake_blender(directory)
    draw = ModuleType('loopcut.ui.draw')
    draw.measure = lambda font, size, text: len(text) * size * .6
    draw.render = Mock()
    draw.retain_images = Mock()
    requests, errors = [], []
    sys.path.insert(0, str(REPO / 'scripts/addons_core'))
    with ExitStack() as stack:
        stack.enter_context(patch.dict(os.environ, env, clear=True))
        stack.enter_context(patch.dict(sys.modules, {'bpy': bpy, 'bpy.utils': bpy.utils,
            'bpy.utils.previews': bpy.utils.previews, 'loopcut.ui.draw': draw}))
        stack.enter_context(patch.object(threading, 'excepthook', lambda args: errors.append(args.exc_value)))
        names = ('account', 'agent', 'cloud', 'cloud_http', 'config', 'credentials', 'conversations',
                 'mainthread', 'state', 'settings', 'workers', 'chatgpt_responses', 'codex_app')
        m = SimpleNamespace(**{name: importlib.import_module('loopcut.' + name) for name in names})
        host = importlib.import_module('loopcut.ui.host')
        stack.enter_context(patch.object(m.config, '_find_env_file', return_value=None))
        stack.enter_context(patch.object(m.config, '_preference_values', return_value={}))
        stack.enter_context(patch.object(m.settings, 'preferences', return_value=None))
        stack.enter_context(patch.object(m.conversations, 'save'))
        stack.enter_context(patch.object(m.agent, '_redraw'))

        def record(transport):
            def send(request, *args, **kwargs):
                requests.append({'path': urlsplit(request.full_url).path, 'method': request.get_method(),
                    'auth': any(k.lower() == 'authorization' for k, _ in request.header_items()),
                    'headers': {k.lower(): v for k, v in request.header_items() if k.lower() != 'authorization'},
                    'body': json.loads(request.data) if request.data else None})
                return transport(request, *args, **kwargs)
            return send
        stack.enter_context(patch.object(m.cloud_http, 'urllib_transport', record(m.cloud_http.urllib_transport)))
        stack.enter_context(patch.object(urllib.request, 'urlopen', record(urllib.request.urlopen)))

        # Registration, panel timer and the actual post-sign-in callback all see HTML 404s.
        m.cloud.register()
        wait_for_cloud(m, errors)
        anonymous_rows = signed_out_click(m, host, requests, errors, mode)
        m.account._store_key(key)
        wait_for_cloud(m, errors)
        runtime = m.cloud._runtime
        check(runtime.signed_in, 'sign-in callback updated the cloud identity')
        refreshed = runtime.refresh()
        check(refreshed == (mode != 'prod'), 'manifest refresh handled the server surface')
        if mode == 'prod':
            m.account._refresh_account(key)
            check(not m.account.status()['error'] and len(m.account.models()) == 2, 'production me/models still work after sign-in')
        m.cloud.panel_seen()
        check(m.cloud._timer() == 10, 'panel timer remains usable')
        wait_for_cloud(m, errors)
        session = m.state.session()
        host.draw_area()
        panel = host._cloud_panel_state(session)
        expected = [d['name'] for d in runtime.manifest['tools'] if d['status'] == 'coming_soon']
        check([row['name'] for row in panel['coming_soon']] == expected, 'panel rows match the manifest')
        check(not panel['cloud_message'], 'panel has no alarming catalog message')
        if mode == 'prod':
            check(not expected and not panel['credits'] and not m.cloud.prompt_index_available(),
                  'older service has no coming-soon rows, invented credits or prompt index')
        else:
            check(bool(expected) and m.cloud.prompt_index_available(), 'beta surface supplies coming-soon rows and prompt index')
        flat = m.agent._tool_schemas()
        wire = json.dumps([flat, m.chatgpt_responses.to_tools(flat), m.codex_app.dynamic_tools()])
        check(all(m.cloud.PREFIX + name not in wire for name in expected), 'coming-soon tools absent from flat and Codex schemas')
        namespace = next((row['tools'] for row in m.chatgpt_responses.to_tools(flat)
                          if row.get('name') == m.cloud.NAMESPACE), [])
        check(not set(expected).intersection(row['name'] for row in namespace), 'coming-soon tools absent from Responses namespace')
        before = runtime.client.request('GET', '/mock/state')['events'] if mode == 'mock' else None
        start, way = len(requests), None
        if expected:
            way = vote_click(m, host, session, requests, errors, expected[0], signed_in=True)
            check(way != 'interest' or runtime.interests[expected[0]] == 'thanks', 'signed in: the interest event was accepted')
            # A second click takes the vote back: a DELETE on a votes server; without votes it stays here.
            voted = len(requests)  # After any take-back of a vote adopted at sign-in (vote_click).
            host._do_action(session, ('vote', expected[0]))
            wait_for_cloud(m, errors)
            deletes = [r for r in requests[voted:] if r['method'] == 'DELETE']
            check(expected[0] not in runtime.votes['mine'] and len(deletes) == (way == 'votes')
                  and all(r['auth'] and r['path'] == '/v1/votes/' + expected[0] for r in deletes)
                  and len([r for r in requests[start:] if r['path'] == '/v1/events']) <= 2,
                  'signed in: a second click takes the vote back and sends no second event')
            leave_votes(host, session)
        else:
            host._do_action(session, ('votes_open', None))
            wait_for_cloud(m, errors)
            host._do_action(session, ('vote', 'voice_line'))
            wait_for_cloud(m, errors)
            check(not any(r['path'].startswith('/v1/votes/') or r['path'] == '/v1/events' for r in requests[start:]),
                  'absent rows send no vote or event')
            host._do_action(session, ('history_close', None))
        if mode == 'mock':
            check(runtime.client.request('GET', '/mock/state')['events'] == before + (way == 'interest'),
                  'mock recorded exactly one event for an interest fallback')

        for model, orchestration in (('fast', 'false'), ('pro', 'true')):
            with patch.dict(os.environ, {'LOOPCUT_MODEL': model, 'LOOPCUT_ORCHESTRATE': orchestration}):
                session = m.state.new_session()
                session['messages'] = [{'role': 'user', 'content': 'Reply with a short greeting. No tool calls are needed.'}]
                turn = m.agent.Turn()
                with patch.object(runtime, 'refresh', side_effect=AssertionError('network during configure')):
                    m.agent._configure(turn, session)
                expected_spec = m.agent.ORCH_SPEC if model == 'pro' and mode != 'prod' else m.agent.SINGLE_SPEC
                check(turn.spec is expected_spec, model + ' selected ' + expected_spec.role)
                if mode == 'prod':
                    check(turn.roles is None and turn.spec.on_turn_start is None
                          and 'delegate' not in {r['function']['name'] for r in turn.spec.schemas()},
                          model + ' has no workers, delegate or router')
                start = len(requests)
                def no_tool(*_):
                    raise AssertionError('Smoke model attempted a scene/tool action')
                m.agent.run_loop(session, turn, turn.spec, run_tool=no_tool, ensure_checkpoint=no_tool)
                check(turn.outcome == 'completed', model + ' completed a hosted turn')
                chats = [r for r in requests[start:] if r['path'] == '/v1/chat/completions']
                identities = [r['headers'].get('x-loopcut-prompt') for r in chats]
                wanted = ([None] if mode == 'prod' else ['single'] if model == 'fast' else ['router', 'orchestrator'])
                check(identities == wanted, model + ' sent the expected prompt headers')
                if mode == 'prod':
                    check(chats[-1]['body']['messages'][0]['content'] == m.agent._system_prompt(session),
                          model + ' sent the open system prompt')
                elif mode == 'mock':
                    upstream = runtime.client.request('GET', '/mock/upstream')
                    check(upstream['prompt'] == expected_spec.prompt_id and upstream['messages'][0]['role'] == 'system',
                          model + ' prompt expanded on the mock')
        if mode != 'prod':
            session = m.state.new_session()
            session['messages'] = [{'role': 'user', 'content': 'Reply with a short greeting.'}]
            completion = m.agent._request(session, m.agent.Turn(), m.config.load(), m.workers.SPEC('modeling', save=lambda _: None))
            chats = [r for r in requests if r['path'] == '/v1/chat/completions']
            check(bool(completion.text) and chats[-1]['headers'].get('x-loopcut-prompt') == 'worker', 'worker request carries its hosted prompt id')
            if mode == 'mock':
                upstream = runtime.client.request('GET', '/mock/upstream')
                check(upstream['prompt'] == 'worker' and upstream['messages'][0]['role'] == 'system',
                      'worker prompt expanded on the mock')
        else:
            check(all('x-loopcut-prompt' not in r['headers'] for r in server_requests), 'NO production-stub request carried x-loopcut-prompt')
            check(not any(r['path'] == '/v1/events' for r in server_requests), 'production stub received no events')
        m.cloud.unregister()
        wait_for_cloud(m, errors)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--prod-stub', action='store_true')
    mode.add_argument('--mock', action='store_true')
    mode.add_argument('--base-url')
    parser.add_argument('--mock-path', type=Path, default=DEFAULT_MOCK)
    parser.add_argument('--key-env')
    args = parser.parse_args(argv)
    if args.base_url and (not args.key_env or not os.environ.get(args.key_env)):
        parser.error('--base-url requires --key-env naming a populated environment variable')
    with tempfile.TemporaryDirectory(prefix='loopcut-beta-') as folder, ExitStack() as stack:
        directory = Path(folder)
        if args.prod_stub:
            url, requests = stack.enter_context(prod_stub())
            exercise(url, 'lc_smoke', 'prod', directory, requests)
        elif args.mock:
            url = stack.enter_context(platform_mock(args.mock_path, directory))
            exercise(url, 'lc_demo', 'mock', directory)
        else:
            exercise(args.base_url, os.environ[args.key_env], 'beta', directory)
    print('PASS beta server compatibility', flush=True)


if __name__ == '__main__':
    try:
        main()
    except Exception:
        traceback.print_exc()
        print('FAIL beta server compatibility', flush=True)
        sys.exit(1)
